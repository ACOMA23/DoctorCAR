def translate(text: str, language: str) -> str:
    if language == "ar":
        return STATES_AR.get(text, text)
    for state, arabic in STATES_AR.items():
        if text == arabic:
            return state.replace("_", " ").title()
    # Longest phrases first, one pass prevents translating inserted text twice.
    import re

    pattern = "|".join(re.escape(k) for k in sorted(AR_EN, key=len, reverse=True))
    return re.sub(pattern, lambda match: AR_EN[match.group()], text)
